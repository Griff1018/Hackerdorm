"""Social content autopilot + calendar for Enterprise Buddy.

- Content plan: when auto-posting is on (the default), the next few post slots are planned ahead from the schedule
  (every N days at a time), each featuring a menu item. The AI writes the caption when a slot is due; the owner can
  abort any slot on the Social posts page before it goes out.
- Event posts: a menu update (new item or price change) or a new business event adds a post slot ~30 minutes ahead,
  so the owner can still abort it.
- Images: generated by an image API when one is configured (OPENAI_API_KEY), otherwise a preset branded poster
  drawn locally with Pillow. Everything is SIMULATED posting.
- Calendar: one list of dated things (posts, events, customer orders, money, tasks, supplier orders, checkpoints).
"""
from __future__ import annotations

import base64
import hashlib
import io
import json
import os
import re
import urllib.request
import uuid
from collections import defaultdict
from datetime import datetime, timedelta

import automations as auto
import workspace as ws

PLAN_AHEAD = 3            # scheduled slots kept planned ahead
EVENT_DELAY_MIN = 30      # an event/menu post goes out this long after the change (time to abort)


def _now():
    return auto.now()


def _parse(t):
    try:
        dt = datetime.fromisoformat(str(t))
        return dt if dt.tzinfo else dt.replace(tzinfo=auto.TZ)
    except (TypeError, ValueError):
        return None


# ---------------------------------------------------------------- content plan (slots)

def _slots(d, bid):
    return d.setdefault("autopost_plan", {}).setdefault(bid, [])


def plan(bid: str) -> list[dict]:
    return sorted(auto.load().get("autopost_plan", {}).get(bid, []), key=lambda s: s["at"])


def add_slot(bid: str, kind: str, at: datetime, topic: str, context: str = "", reason: str = "", ref: str = "") -> dict:
    s = {"id": "PS" + uuid.uuid4().hex[:6], "kind": kind, "at": at.isoformat(timespec="minutes"), "topic": topic[:120], "context": context[:600],
         "reason": reason[:160], "ref": ref, "status": "planned", "created_at": auto.iso()}
    with auto.LOCK:
        d = auto.load()
        sl = _slots(d, bid)
        if ref and any(x.get("ref") == ref and x["status"] == "planned" for x in sl):
            return next(x for x in sl if x.get("ref") == ref and x["status"] == "planned")
        sl.append(s)
        auto.log(d, f"Planned {kind} post for {s['at'].replace('T', ' ')}: {topic}" + (f" ({reason})" if reason else ""), "post")
        auto.save(d)
    return s


def set_slot(bid: str, sid: str, **kv) -> dict:
    with auto.LOCK:
        d = auto.load()
        s = next((x for x in _slots(d, bid) if x["id"] == sid), None)
        if not s:
            raise ValueError("unknown planned post")
        s.update(kv)
        if kv.get("status") == "cancelled":
            auto.log(d, f"Owner aborted planned post {sid} ({s['topic']})", "post")
        auto.save(d)
        return s


def topics(bid: str) -> list[str]:
    import settings as appset
    menu = [m["item"] for m in appset.shop_menu(bid)]
    if menu:
        return menu
    b = ws.business(bid) or {}
    btype = str(b.get("type") or "").strip()
    parts = re.split(r"\s+[—–-]\s+", btype)
    items = [x.strip().rstrip(".") for x in re.split(r",|\band\b", parts[1] if len(parts) > 1 else parts[0]) if x.strip()]
    return [i[:1].upper() + i[1:] for i in items][:6] or [b.get("name") or "Our products"]


def _next_time(base: datetime, cfg: dict) -> datetime:
    hh, mm = (int(x) for x in str(cfg.get("time") or "12:30").split(":")[:2])
    t = base.replace(hour=hh, minute=mm, second=0, microsecond=0)
    return t if t > base else t + timedelta(days=1)


def ensure_plan(bid: str) -> None:
    """Keep PLAN_AHEAD scheduled slots planned (only while auto-posting is on)."""
    cfg = auto.autopost(bid)
    if not cfg.get("enabled"):
        return
    sl = plan(bid)
    tp_now = set(topics(bid))
    if any(s["kind"] == "scheduled" and s["status"] == "planned" and _parse(s["at"]) > _now() and s["topic"] not in tp_now for s in sl):
        with auto.LOCK:
            d = auto.load()
            d.setdefault("autopost_plan", {})[bid] = [s for s in _slots(d, bid) if not (s["kind"] == "scheduled" and s["status"] == "planned"
                                                                                      and _parse(s["at"]) > _now() and s["topic"] not in tp_now)]
            auto.save(d)
        sl = plan(bid)
    upcoming = [s for s in sl if s["kind"] == "scheduled" and s["status"] in ("planned", "cancelled") and _parse(s["at"]) > _now()]
    if len(upcoming) >= PLAN_AHEAD:
        return
    tp = topics(bid)
    n = len([s for s in sl if s["kind"] == "scheduled"])
    base = max([_parse(s["at"]) for s in upcoming] + [_now()])
    step = timedelta(days=int(cfg.get("every_days") or 1))
    t = _next_time(_now(), cfg) if not upcoming else base + step
    for i in range(PLAN_AHEAD - len(upcoming)):
        add_slot(bid, "scheduled", t, tp[(n + i) % len(tp)], reason=f"every {cfg.get('every_days')} day(s) at {cfg.get('time')}")
        t += step


def replan(bid: str) -> None:
    """Schedule changed: drop future planned scheduled slots and plan again."""
    with auto.LOCK:
        d = auto.load()
        d.setdefault("autopost_plan", {})[bid] = [s for s in _slots(d, bid) if not (s["kind"] == "scheduled" and s["status"] == "planned" and _parse(s["at"]) > _now())]
        auto.save(d)
    ensure_plan(bid)


def due(bid: str) -> list[dict]:
    return [s for s in plan(bid) if s["status"] == "planned" and _parse(s["at"]) <= _now()]


# ---------------------------------------------------------------- events + menu updates → posts

def events(bid: str | None = None) -> list[dict]:
    rows = auto.load().get("events", [])
    return sorted([e for e in rows if bid in (None, ws.ALL) or e["business_id"] == bid], key=lambda e: e["date"] + (e.get("time") or ""))


def add_event(bid: str, title: str, date: str, time: str = "", note: str = "") -> dict:
    title = str(title).strip()[:120]
    if not title:
        raise ValueError("Give the event a name.")
    try:
        datetime.fromisoformat(str(date)[:10])
    except ValueError:
        raise ValueError("Pick the event date.")
    e = {"id": "EV" + uuid.uuid4().hex[:6], "business_id": bid, "title": title, "date": str(date)[:10], "time": str(time or "")[:5],
         "note": str(note or "")[:300], "created_at": auto.iso()}
    with auto.LOCK:
        d = auto.load()
        d.setdefault("events", []).append(e)
        auto.save(d)
    when = e["date"] + (" " + e["time"] if e["time"] else "")
    add_slot(bid, "event", _now() + timedelta(minutes=EVENT_DELAY_MIN), title,
             f"Announce our event: {title} on {when}. {e['note']}".strip(), reason="new event", ref="event:" + e["id"])
    day_before = _parse(e["date"] + "T" + (auto.autopost(bid).get("time") or "12:30")) - timedelta(days=1)
    if day_before > _now() + timedelta(hours=2):
        add_slot(bid, "event", day_before, title, f"Reminder: our event {title} is tomorrow ({when}). {e['note']}".strip(),
                 reason="event reminder", ref="event-reminder:" + e["id"])
    return e


def delete_event(eid: str) -> bool:
    with auto.LOCK:
        d = auto.load()
        rows = d.get("events", [])
        keep = [e for e in rows if e["id"] != eid]
        for sl in d.get("autopost_plan", {}).values():
            for s in sl:
                if s.get("ref", "").endswith(":" + eid) and s["status"] == "planned":
                    s["status"] = "cancelled"
        d["events"] = keep
        auto.save(d)
        return len(keep) != len(rows)


def menu_changed(bid: str, before: list[dict], after: list[dict]) -> None:
    """Called after the shop menu is saved: new items and price changes get an announcement post."""
    if not auto.autopost(bid).get("enabled"):
        return
    old = {m["item"].lower(): m for m in before or []}
    for m in after or []:
        o = old.get(m["item"].lower())
        if o is None:
            add_slot(bid, "event", _now() + timedelta(minutes=EVENT_DELAY_MIN), m["item"],
                     f"New on our menu: {m['item']} at MYR {float(m['price']):.2f}.", reason="new menu item", ref="menu:new:" + m["item"].lower())
        elif abs(float(o.get("price") or 0) - float(m.get("price") or 0)) >= 0.01:
            add_slot(bid, "event", _now() + timedelta(minutes=EVENT_DELAY_MIN), m["item"],
                     f"Price update: {m['item']} is now MYR {float(m['price']):.2f}.", reason="menu price change", ref=f"menu:price:{m['item'].lower()}:{m['price']}")
    if {m["item"].lower() for m in after or []} != set(old):
        replan(bid)  # scheduled posts rotate through the new menu


# ---------------------------------------------------------------- images: API if configured, otherwise a preset poster

PALETTES = [("#243b32", "#e6ece2", "#f2c14e"), ("#7a2e2e", "#fbe9e7", "#f6bd60"), ("#1d4e89", "#e5eefa", "#f9c74f"),
            ("#5b3a29", "#f6efe6", "#e9a03b"), ("#2d6a4f", "#e9f5ee", "#ffb703"), ("#3d2c8d", "#ece9fb", "#f4a261")]


def _font(size, bold=False):
    from PIL import ImageFont
    for f in (["arialbd.ttf", "DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"] if bold else
              ["arial.ttf", "DejaVuSans.ttf", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]):
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def _wrap(draw, text, font, width):
    words, lines, cur = str(text).split(), [], ""
    for w in words:
        t = (cur + " " + w).strip()
        if draw.textlength(t, font=font) <= width:
            cur = t
        else:
            if cur:
                lines.append(cur)
            cur = w
    return lines + ([cur] if cur else [])


def poster(bid: str, headline: str, sub: str = "", tag: str = "") -> bytes:
    """A 1080×1080 branded poster: business name, headline (item/event), price or date, call to action."""
    from PIL import Image, ImageDraw
    b = ws.business(bid) or {}
    dark, light, accent = PALETTES[int(hashlib.md5(bid.encode()).hexdigest(), 16) % len(PALETTES)]
    img = Image.new("RGB", (1080, 1080), light)
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, 1080, 210], fill=dark)
    d.ellipse([800, 620, 1300, 1120], fill=accent)
    d.text((70, 70), str(b.get("name") or "Our shop")[:34], font=_font(58, True), fill=light)
    if tag:
        tw = d.textlength(tag.upper(), font=_font(34, True))
        d.rounded_rectangle([70, 270, 70 + tw + 50, 330], radius=28, fill=accent)
        d.text((95, 276), tag.upper(), font=_font(34, True), fill=dark)
    y = 380
    for line in _wrap(d, headline, _font(96, True), 780)[:3]:
        d.text((70, y), line, font=_font(96, True), fill=dark)
        y += 112
    if sub:
        for line in _wrap(d, sub, _font(48), 740)[:2]:
            d.text((70, y + 20), line, font=_font(48), fill=dark)
            y += 60
    area = str(b.get("area") or "").split(",")[0]
    d.rectangle([0, 950, 1080, 1080], fill=dark)
    d.text((70, 990), ("Order by DM or our online shop" + (f" · {area}" if area else ""))[:60], font=_font(36), fill=light)
    out = io.BytesIO()
    img.save(out, "PNG")
    return out.getvalue()


def api_image(prompt: str) -> bytes | None:
    """Generated image when an image API key is configured (OpenAI Images); None otherwise or on any failure."""
    key = os.environ.get("OPENAI_API_KEY") or os.environ.get("IMAGE_API_KEY")
    if not key:
        return None
    try:
        req = urllib.request.Request("https://api.openai.com/v1/images/generations", method="POST",
                                     data=json.dumps({"model": os.environ.get("IMAGE_MODEL", "gpt-image-1"), "prompt": prompt[:900], "size": "1024x1024"}).encode(),
                                     headers={"Content-Type": "application/json", "Authorization": "Bearer " + key})
        r = json.loads(urllib.request.urlopen(req, timeout=90).read())
        return base64.b64decode(r["data"][0]["b64_json"])
    except Exception:
        return None


def image_for(bid: str, headline: str, sub: str = "", tag: str = "") -> dict:
    """Save the post image as media: API-generated if possible, else the preset poster."""
    b = ws.business(bid) or {}
    data = api_image(f"Appetising, bright social media photo for a small Malaysian business ({b.get('type')}): {headline}. {sub}. No text.")
    source = "generated by image API" if data else "preset poster (no image API configured)"
    rec = auto.save_media(("gen_" if data else "poster_") + uuid.uuid4().hex[:6] + ".png", data or poster(bid, headline, sub, tag),
                          f"{headline} — {source}", bid)
    return dict(rec, image_source=source)


# ---------------------------------------------------------------- a post the owner asked for in chat

def create_post(bid: str, spec: dict) -> dict:
    caption = str(spec.get("caption") or "").strip()
    if not caption:
        raise ValueError("The post needs a caption.")
    topic = str(spec.get("topic") or caption.split("\n")[0])[:80]
    tags = spec.get("hashtags") or []
    tags = [t if str(t).startswith("#") else "#" + str(t) for t in (tags if isinstance(tags, list) else str(tags).split())][:15]
    platforms = [p for p in (spec.get("platforms") or ["Instagram"]) if p in ("Instagram", "Facebook", "TikTok")] or ["Instagram"]
    when = str(spec.get("when") or "now").strip()
    at = None
    if when.lower() not in ("now", ""):
        at = _parse(when)
        if not at or at <= _now():
            at = None
    img = image_for(bid, topic, str(spec.get("subtitle") or "")[:80], "New post")
    post = auto.add_post({"business_id": bid, "media_ids": [img["id"]], "caption": caption, "hashtags": tags, "platforms": platforms,
                          "topic": topic, "from_chat": True, "scheduled_for": at.isoformat(timespec="seconds") if at else None})
    return {"post": post, "image": "/files/" + img["file"], "image_source": img.get("image_source")}


def delete_post(pid: str) -> bool:
    with auto.LOCK:
        d = auto.load()
        keep = [p for p in d.get("posts", []) if p["id"] != pid]
        gone = len(keep) != len(d.get("posts", []))
        d["posts"] = keep
        if gone:
            auto.log(d, f"Post {pid} removed by the owner (Undo)", "post")
        auto.save(d)
        return gone


# ---------------------------------------------------------------- calendar: every dated thing in one list

def calendar(bid: str) -> list[dict]:
    import inbox
    import money as mon
    names = {b["id"]: b["name"] for b in ws.businesses()}
    bids = [b["id"] for b in ws.businesses()] if bid == ws.ALL else [bid]
    out = []

    def add(bid_, date, kind, title, time="", status="", ref="", tab=""):
        if date:
            out.append({"date": str(date)[:10], "time": str(time or "")[:5], "kind": kind, "title": title[:120], "status": status,
                        "ref": ref, "tab": tab, "business_id": bid_, "business": names.get(bid_, "")})
    a = auto.load()
    for b in bids:
        for s in a.get("autopost_plan", {}).get(b, []):
            add(b, s["at"][:10], "post", ("Event post: " if s["kind"] == "event" else "Post: ") + s["topic"], s["at"][11:16], s["status"], s["id"], "automations")
        for p in a.get("posts", []):
            if p.get("business_id") == b and not p.get("auto"):
                when = p.get("scheduled_for") or p.get("posted_at") or p.get("created_at")
                add(b, str(when)[:10], "post", "Post: " + str(p.get("caption") or "")[:60], str(when)[11:16], p.get("status", ""), p["id"], "automations")
        for e in a.get("events", []):
            if e["business_id"] == b:
                add(b, e["date"], "event", e["title"], e.get("time"), "", e["id"], "automations")
        for o in a.get("orders", []):
            if o.get("business_id") == b:
                add(b, str(o["created_at"])[:10], "reorder", f"Supplier order: {o.get('quantity')} {o.get('material')} · MYR {o.get('total_myr')}",
                    str(o["created_at"])[11:16], o["status"], o["id"], "inventory")
        for o in inbox.orders(b, None):
            add(b, str(o["created_at"])[:10], "order", f"{o.get('customer')} · MYR {o.get('total')}" + (f" · {o.get('when')}" if o.get("when") else ""),
                str(o["created_at"])[11:16], o["status"], o["id"], "orders")
        day = defaultdict(lambda: [0.0, 0.0])
        for r in mon.ledger(b)["entries"]:
            day[r["date"]][0 if r["direction"] == "in" else 1] += r["amount"]
        for dte, (i, o) in day.items():
            add(b, dte, "money", f"In MYR {i:.2f}" + (f" · out MYR {o:.2f}" if o else ""), "", "", dte, "money")
        for t in ws.todos(b):
            when = t.get("due") or (t.get("done_at") if t.get("done") else t.get("created_at"))
            add(b, str(when)[:10], "todo", t["title"], "", "done" if t.get("done") else ("due" if t.get("due") else "added"), t["id"], "roadmap")
        for c in ws.checkpoints(b):
            add(b, str(c.get("at"))[:10], "checkpoint", "Checkpoint: " + c["title"], "", "", c["id"], "roadmap")
    return sorted(out, key=lambda e: (e["date"], e["time"]))
